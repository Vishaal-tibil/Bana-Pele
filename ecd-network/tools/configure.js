#!/usr/bin/env node
// configure.js -- writes everything a node needs to join the ECD network.
//
//   node tools/configure.js [--mode local|docker]
//
// For every node in config/nodes/*.json it:
//   1. makes the node's keys if they are missing (../tools/gen-node-identity.sh,
//      the repo's existing script; private keys stay in .keys/, never in git);
//   2. writes the node's ONIX adapter config and routing files to
//      .generated/onix/<node>/ (they hold the private key, so .generated/ is
//      gitignored);
//   3. writes .generated/registry.json: one record per node for ecd-registry.
//
// mode "local" : every process on 127.0.0.1 with the ports in the node file.
// mode "docker": service names on the compose network (onix-<id>, <id>-app...).
// Nothing outside ecd-network/ is written.

'use strict';
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');
const { addresses } = require('../lib/addresses');
const { webhookSecret } = require('../lib/kit');

const ROOT = path.resolve(__dirname, '..');
const REPO = path.resolve(ROOT, '..');
const mode = (process.argv.includes('--mode') ? process.argv[process.argv.indexOf('--mode') + 1] : process.env.ECD_MODE) || 'local';
if (!['local', 'docker'].includes(mode)) { console.error('mode must be local or docker'); process.exit(1); }

const network = JSON.parse(fs.readFileSync(path.join(ROOT, 'config/network.json'), 'utf8'));
const KEYS = path.join(ROOT, '.keys');
const GEN = path.join(ROOT, '.generated');

function readNodes() {
  const dir = path.join(ROOT, 'config/nodes');
  return fs.readdirSync(dir).filter((f) => f.endsWith('.json')).sort()
    .map((f) => JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8')));
}

function readEnv(file) {
  const out = {};
  for (const line of fs.readFileSync(file, 'utf8').split('\n')) {
    const m = line.match(/^([A-Z_]+)=(.*)$/);
    if (m) out[m[1]] = m[2];
  }
  return out;
}

function ensureKeys(node) {
  const file = path.join(KEYS, `${node.subscriberId}.env`);
  if (!fs.existsSync(file)) {
    execFileSync('bash', [path.join(REPO, 'tools/gen-node-identity.sh'), node.subscriberId], {
      env: { ...process.env, OUT: KEYS }, stdio: ['ignore', 'ignore', 'inherit'],
    });
  }
  return readEnv(file);
}

// Addresses come from lib/addresses.js, the same module the apps use.
function addr(node) {
  const a = addresses(node, network, mode, webhookSecret(node));
  return { ...a, httpPort: a.adapterPort, plugins: mode === 'local' ? (process.env.ONIX_PLUGINS || './plugins') : './plugins' };
}

const REQUESTS = ['discover', 'select', 'init', 'confirm', 'status', 'track', 'update', 'cancel', 'rate', 'support'];
const ANSWERS = REQUESTS.map((a) => `on_${a}`);

function routing(targetType, endpoints, url) {
  return [
    'routingRules:',
    `  - version: "${network.version}"`,
    `    targetType: "${targetType}"`,
    ...(url ? ['    target:', `      url: "${url}"`] : []),
    '    endpoints:',
    ...endpoints.map((e) => `      - ${e}`),
    '',
  ].join('\n');
}

function pluginsBlock(node, keys, a, routingFile, role) {
  return `      plugins:
        registry:
          id: registry
          config:
            url: ${a.registry}
            cacheTTL: ${process.env.ECD_REGISTRY_CACHE_TTL || network.registryCacheTTL || '60s'}
            retry_max: 3
            retry_wait_min: 100ms
            retry_wait_max: 500ms
        keyManager:
          id: simplekeymanager
          config:
            subscriberId: ${node.subscriberId}
            keyId: ${keys.KEY_ID}
            signingPrivateKey: ${keys.SIGNING_PRIVATE_KEY}
            signingPublicKey: ${keys.SIGNING_PUBLIC_KEY}
            encrPrivateKey: ${keys.ENCR_PRIVATE_KEY}
            encrPublicKey: ${keys.ENCR_PUBLIC_KEY}
        cache:
          id: cache
          config:
            addr: ${a.redis}
        schemaValidator:
          id: schemav2validator
          config:
            cacheTTL: "3600"
        signValidator:
          id: signvalidator
        router:
          id: router
          config:
            routingConfig: ${routingFile}
        signer:
          id: signer
        middleware:
          - id: reqpreprocessor
            config:
              contextKeys: transactionId,messageId
              role: ${role}`;
}

function adapterYaml(node, keys, a, cfgDir) {
  const role = a.side;
  const f = (name) => (mode === 'local' ? path.join(cfgDir, name) : `/app/config/${name}`);
  return `# Generated by tools/configure.js (mode ${mode}) -- do not edit, do not commit: holds the private key.
appName: "onix-ecd-${node.id}"
log:
  level: info
  destinations:
    - type: stdout
  contextKeys:
    - transactionId
    - messageId
http:
  port: ${a.httpPort}
  timeout:
    read: 30
    write: 30
    idle: 30
pluginManager:
  root: ${a.plugins}
  becknConstants:
    disableRemoteRefresh: true
modules:
  - name: ${role}TxnReceiver
    path: /${role}/receiver/
    handler:
      type: std
      role: ${role}
      subscriberId: ${node.subscriberId}
      httpClientConfig:
        responseHeaderTimeout: 5s
${pluginsBlock(node, keys, a, f(`routing-${role}-receiver.yaml`), role)}
      steps:
        - validateSign
        - addRoute
        - validateSchema
        - signAck
  - name: ${role}TxnCaller
    path: /${role}/caller/
    handler:
      type: std
      role: ${role}
      subscriberId: ${node.subscriberId}
      httpClientConfig:
        responseHeaderTimeout: 5s
${pluginsBlock(node, keys, a, f(`routing-${role}-caller.yaml`), role)}
      steps:
        - addRoute
        - validateSchema
        - sign
        - validateAckSign
`;
}

// One compose file for the whole network, made from the node files, so a new
// node needs no hand edits. Paths are relative to .generated/.
function compose(nodes) {
  const image = process.env.ONIX_IMAGE || 'fidedocker/onix-adapter:latest';
  const lines = [
    '# Generated by tools/configure.js --mode docker. Do not edit; do not commit (it is in .generated/).',
    '#   docker compose -f .generated/docker-compose.yml up -d',
    'name: ecd-network',
    'services:',
    '  ecd-registry:',
    '    image: node:20-alpine',
    '    working_dir: /ecd',
    '    command: ["node", "registry/server.js"]',
    '    environment: ["REGISTRY_FILE=/ecd/.generated/registry.json", "HOST=0.0.0.0"]',
    '    volumes: ["..:/ecd:ro"]',
    `    ports: ["127.0.0.1:${network.registryPort}:3030"]`,
    '    restart: unless-stopped',
  ];
  for (const n of nodes) {
    const app = n.role === 'BAP' ? 'nodes/journey/server.js' : 'nodes/provider/server.js';
    lines.push(
      `  redis-${n.id}:`,
      '    image: redis:7-alpine',
      '    command: ["redis-server", "--save", "", "--appendonly", "no"]',
      '    restart: unless-stopped',
      `  onix-${n.id}:`,
      `    image: ${image}`,
      '    platform: linux/amd64',
      '    command: ["./server", "--config=/app/config/adapter.yaml"]',
      `    volumes: ["./onix/${n.id}:/app/config:ro"]`,
      `    ports: ["127.0.0.1:${n.ports.onix}:8080"]`,
      `    depends_on: [redis-${n.id}, ecd-registry]`,
      '    restart: unless-stopped',
      `  ${n.id}-app:`,
      '    image: node:20-alpine',
      '    working_dir: /ecd',
      `    command: ["node", "${app}"]`,
      '    environment:',
      `      - "NODE_FILE=/ecd/config/nodes/${n.id}.json"`,
      '      - "ECD_MODE=docker"',
      '      - "ECD_DEBUG_BODIES=${ECD_DEBUG_BODIES:-0}"',
      '      - "ECD_ASK_TIMEOUT_MS=${ECD_ASK_TIMEOUT_MS:-20000}"',
      '    volumes: ["..:/ecd:ro", "../data:/ecd/data"]',
      `    ports: ["127.0.0.1:${n.ports.app}:${n.ports.app}"]`,
      `    depends_on: [onix-${n.id}]`,
      '    restart: unless-stopped',
    );
  }
  return lines.join('\n') + '\n';
}

function main() {
  fs.mkdirSync(KEYS, { recursive: true, mode: 0o700 });
  const nodes = readNodes();
  const registry = { networkId: network.networkId, generatedBy: 'tools/configure.js', mode, subscribers: [] };

  for (const node of nodes) {
    const keys = ensureKeys(node);
    const a = addr(node);
    const dir = path.join(GEN, 'onix', node.id);
    // Local: owner-only. Docker: the adapter container may run as another
    // user, so the config must be world-readable (a dev laptop only).
    const open = mode === 'docker';
    fs.mkdirSync(dir, { recursive: true });
    fs.chmodSync(dir, open ? 0o755 : 0o700);
    const isBap = node.role === 'BAP';
    fs.writeFileSync(path.join(dir, `routing-${a.side}-caller.yaml`),
      isBap ? routing('bpp', REQUESTS) : routing('bap', ANSWERS));
    fs.writeFileSync(path.join(dir, `routing-${a.side}-receiver.yaml`),
      routing('url', isBap ? ANSWERS : REQUESTS, a.webhook));
    fs.writeFileSync(path.join(dir, 'adapter.yaml'), adapterYaml(node, keys, a, dir));
    fs.chmodSync(path.join(dir, 'adapter.yaml'), open ? 0o644 : 0o600);
    registry.subscribers.push({
      subscriber_id: node.subscriberId,
      name: node.name,
      type: node.role,
      url: a.receiver,
      key_id: keys.KEY_ID,
      signing_public_key: keys.SIGNING_PUBLIC_KEY,
      encr_public_key: keys.ENCR_PUBLIC_KEY,
      // "status": "paused" in the node file pauses it: adapters then refuse its messages.
      status: node.status === 'paused' ? 'UNSUBSCRIBED' : 'SUBSCRIBED',
    });
    console.log(`  ${node.id.padEnd(10)} ${node.role}  ${node.subscriberId}  key ${keys.KEY_ID}`);
  }
  fs.writeFileSync(path.join(GEN, 'registry.json'), JSON.stringify(registry, null, 2) + '\n');
  if (mode === 'docker') {
    fs.writeFileSync(path.join(GEN, 'docker-compose.yml'), compose(nodes));
    console.log('  compose    .generated/docker-compose.yml');
  }
  console.log(`  registry   ${registry.subscribers.length} subscribers, network ${network.networkId}, mode ${mode}`);
}

main();
